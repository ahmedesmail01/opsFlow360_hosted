-- 01. Seed six reusable asset types
--------------------------------------------------------------------------------

declare
  l_seed_count number;
begin
  merge into of_asset_types t
  using (
    select 'LAPTOP' code, 'Laptop' name,
           'Portable employee computer.' description,
           'Y' requires_serial_no, 36 warranty_months from dual
    union all select 'DESKTOP', 'Desktop',
           'Fixed workstation computer.', 'Y', 36 from dual
    union all select 'MONITOR', 'Monitor',
           'External display device.', 'Y', 36 from dual
    union all select 'MOBILE_PHONE', 'Mobile Phone',
           'Company-managed mobile telephone.', 'Y', 24 from dual
    union all select 'PRINTER', 'Printer',
           'Managed printing device.', 'Y', 24 from dual
    union all select 'FURNITURE', 'Furniture',
           'Individually tracked office furniture.', 'N', 60 from dual
  ) s
  on (t.code = s.code)
  when matched then update set
    t.name = s.name,
    t.description = s.description,
    t.requires_serial_no = s.requires_serial_no,
    t.default_warranty_months = s.warranty_months,
    t.is_active = 'Y',
    t.updated_at = systimestamp,
    t.updated_by = 'P06_SEED'
  when not matched then insert (
    code, name, description, requires_serial_no,
    default_warranty_months, is_active, created_by, updated_by
  ) values (
    s.code, s.name, s.description, s.requires_serial_no,
    s.warranty_months, 'Y', 'P06_SEED', 'P06_SEED'
  );

  select count(*)
    into l_seed_count
    from of_asset_types
   where code in (
     'LAPTOP', 'DESKTOP', 'MONITOR', 'MOBILE_PHONE', 'PRINTER', 'FURNITURE'
   )
     and is_active = 'Y';

  if l_seed_count <> 6 then
    rollback;
    raise_application_error(
      -20242,
      'P06 seed stopped: expected 6 active asset types, found ' ||
      l_seed_count || '.'
    );
  end if;

  commit;
  dbms_output.put_line('P06 reference seed committed: 6 active asset types.');
end;
