  select count(*)
    into l_collision_count
    from user_objects
   where object_name in (
     'OF_ASSET_TYPES', 'OF_ASSETS', 'OF_ASSET_RESERVATIONS',
     'OF_ASSET_ASSIGNMENTS', 'OF_ASSET_REPAIRS',
     'OF_ASSET_STATUS_HISTORY', 'OF_ASSET_API',
