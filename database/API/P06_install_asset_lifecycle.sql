  procedure mark_lost(
    p_asset_id               in  number,
    p_expected_row_version   in  number,
    p_reason_text            in  varchar2,
    p_new_row_version        out number
  ) is
    l_asset       of_assets%rowtype;
    l_actor_id    number;
    l_actor_name  varchar2(255 char);
    l_related_user number;
  begin
    savepoint of_asset_api_action;
    p_new_row_version := null;
    assert_text(p_reason_text, 'Loss reason', 1000);
    lock_asset(p_asset_id, p_expected_row_version, l_asset);
    if l_asset.status_code in ('RETIRED', 'LOST') then
      fail(-20204, 'A retired or lost asset is terminal.');
    end if;
    l_actor_id := of_security_api.current_user_id();
    l_actor_name := of_security_api.current_username();
    l_related_user := null;

    if l_asset.status_code = 'RESERVED' then
      select reserved_for_user_id into l_related_user
        from of_asset_reservations
       where asset_id = l_asset.id and status_code = 'ACTIVE'
         for update;
      update of_asset_reservations
         set status_code = 'RELEASED', released_at = systimestamp,
             released_by_user_id = l_actor_id,
             reason_text = substr('Asset lost: ' || trim(p_reason_text), 1, 1000),
             updated_at = systimestamp, updated_by = l_actor_name
       where asset_id = l_asset.id and status_code = 'ACTIVE';
    elsif l_asset.status_code = 'ASSIGNED' then
      select assigned_to_user_id into l_related_user
        from of_asset_assignments
       where asset_id = l_asset.id and returned_at is null
         for update;
      update of_asset_assignments
         set returned_at = systimestamp, returned_by_user_id = l_actor_id,
             condition_in_code = 'LOST',
             notes = substr(
               case when notes is null then '' else notes || chr(10) end ||
               'Lost: ' || trim(p_reason_text), 1, 2000
             ),
             updated_at = systimestamp, updated_by = l_actor_name
       where asset_id = l_asset.id and returned_at is null;
    elsif l_asset.status_code = 'IN_REPAIR' then
      update of_asset_repairs
         set status_code = 'CANCELLED', closed_at = systimestamp,
             resolution_description = to_clob(
               'Cancelled because asset was marked lost: ' || trim(p_reason_text)
             ),
             row_version = row_version + 1,
             updated_at = systimestamp, updated_by = l_actor_name
       where asset_id = l_asset.id
         and status_code in ('OPEN', 'IN_PROGRESS');
    end if;

    update of_assets
       set status_code = 'LOST', row_version = row_version + 1,
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_asset.id
     returning row_version into p_new_row_version;

    record_event(
      'ASSET_MARKED_LOST', l_asset.id, l_asset.asset_tag,
      l_asset.status_code, 'LOST', l_asset.current_location_id,
      l_asset.current_location_id, l_related_user, null, p_reason_text,
      l_asset.row_version, p_new_row_version
    );
  exception
    when no_data_found then
      rollback to of_asset_api_action;
      fail(-20208, 'The active lifecycle relationship is missing.');
    when others then rollback to of_asset_api_action; raise;
  end mark_lost;

  procedure retire_asset(
    p_asset_id               in  number,
    p_expected_row_version   in  number,
    p_reason_text            in  varchar2,
    p_new_row_version        out number
  ) is
    l_asset      of_assets%rowtype;
    l_actor_name varchar2(255 char);
  begin
    savepoint of_asset_api_action;
    p_new_row_version := null;
    assert_text(p_reason_text, 'Retirement reason', 1000);
    lock_asset(p_asset_id, p_expected_row_version, l_asset);
    if l_asset.status_code not in ('IN_STOCK', 'IN_REPAIR') then
      fail(-20204, 'Retirement is allowed only from IN_STOCK or IN_REPAIR.');
    end if;
    l_actor_name := of_security_api.current_username();

    if l_asset.status_code = 'IN_REPAIR' then
      update of_asset_repairs
         set status_code = 'CANCELLED', closed_at = systimestamp,
             resolution_description = to_clob(
               'Cancelled by retirement: ' || trim(p_reason_text)
             ),
             row_version = row_version + 1,
             updated_at = systimestamp, updated_by = l_actor_name
       where asset_id = l_asset.id
         and status_code in ('OPEN', 'IN_PROGRESS');
    end if;

    update of_assets
       set status_code = 'RETIRED', row_version = row_version + 1,
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_asset.id
     returning row_version into p_new_row_version;

    record_event(
      'ASSET_RETIRED', l_asset.id, l_asset.asset_tag,
      l_asset.status_code, 'RETIRED', l_asset.current_location_id,
      l_asset.current_location_id, null, null, p_reason_text,
      l_asset.row_version, p_new_row_version
    );
  exception
    when others then rollback to of_asset_api_action; raise;
  end retire_asset;
