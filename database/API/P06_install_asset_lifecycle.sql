  function normalized_condition(p_value in varchar2) return varchar2 is
    l_value varchar2(30 char);
  begin
    l_value := of_util_api.normalize_code(p_value);
    if l_value is null
       or l_value not in ('NEW', 'GOOD', 'FAIR', 'DAMAGED', 'LOST') then
      fail(-20200, 'Condition must be NEW, GOOD, FAIR, DAMAGED, or LOST.');
    end if;
    return l_value;
  end normalized_condition;

  procedure validate_money(
    p_amount        in  number,
    p_currency_code in  varchar2,
    p_normalized    out varchar2
  ) is
  begin
    p_normalized := of_util_api.normalize_code(p_currency_code);
    if p_amount is null and p_normalized is not null then
      fail(-20200, 'Currency cannot be supplied without an amount.');
    elsif p_amount is not null then
      if p_amount < 0 then
        fail(-20200, 'Amount cannot be negative.');
      end if;
      if p_normalized is null
         or not regexp_like(p_normalized, '^[A-Z]{3}$') then
        fail(-20200, 'A three-letter uppercase currency code is required.');
      end if;
    end if;
  end validate_money;

  procedure assert_consistent(p_asset in of_assets%rowtype) is
    l_reservations number;
    l_assignments  number;
    l_repairs      number;
    l_valid        boolean := false;
  begin
    select count(*) into l_reservations
      from of_asset_reservations
     where asset_id = p_asset.id and status_code = 'ACTIVE';
    select count(*) into l_assignments
      from of_asset_assignments
     where asset_id = p_asset.id and returned_at is null;
    select count(*) into l_repairs
      from of_asset_repairs
     where asset_id = p_asset.id and status_code in ('OPEN', 'IN_PROGRESS');

    case p_asset.status_code
      when 'IN_STOCK' then
        l_valid := l_reservations = 0 and l_assignments = 0 and l_repairs = 0;
      when 'RESERVED' then
        l_valid := l_reservations = 1 and l_assignments = 0 and l_repairs = 0;
      when 'ASSIGNED' then
        l_valid := l_reservations = 0 and l_assignments = 1 and l_repairs = 0;
      when 'IN_REPAIR' then
        l_valid := l_reservations = 0 and l_assignments = 0 and l_repairs = 1;
      when 'RETIRED' then
        l_valid := l_reservations = 0 and l_assignments = 0 and l_repairs = 0;
      when 'LOST' then
        l_valid := l_reservations = 0 and l_assignments = 0 and l_repairs = 0;
      else
        l_valid := false;
    end case;

    if not l_valid then
      fail(
        -20208,
        'Asset status disagrees with its active reservation, custody, or repair row.'
      );
    end if;
  end assert_consistent;

  procedure lock_asset(
    p_asset_id             in  number,
    p_expected_row_version in  number,
    p_asset                out of_assets%rowtype
  ) is
    e_resource_busy exception;
    pragma exception_init(e_resource_busy, -54);
  begin
    assert_admin;
    if p_asset_id is null or p_expected_row_version is null
       or p_expected_row_version < 1 then
      fail(-20200, 'Asset ID and expected row version are required.');
    end if;

    select * into p_asset
      from of_assets
     where id = p_asset_id
       for update nowait;

    if p_asset.row_version <> p_expected_row_version then
      fail(-20202, 'Asset changed since it was loaded. Refresh and try again.');
    end if;
    assert_consistent(p_asset);
  exception
    when no_data_found then
      fail(-20201, 'Asset does not exist or is no longer available.');
    when e_resource_busy then
      fail(-20203, 'Asset is currently being changed by another session.');
  end lock_asset;

  function state_json(
    p_status_code in varchar2,
    p_row_version in number,
    p_location_id in number,
    p_related_user_id in number
  ) return clob is
    l_json json_object_t := json_object_t();
  begin
    if p_status_code is null then l_json.put_null('statusCode');
    else l_json.put('statusCode', p_status_code); end if;
    if p_row_version is null then l_json.put_null('rowVersion');
    else l_json.put('rowVersion', p_row_version); end if;
    if p_location_id is null then l_json.put_null('locationId');
