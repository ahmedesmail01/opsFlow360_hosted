    if p_related_user_id is null then l_json.put_null('relatedUserId');
    else l_json.put('relatedUserId', p_related_user_id); end if;
    return l_json.to_clob();
  end state_json;

  procedure record_event(
    p_action_code         in varchar2,
    p_asset_id           in number,
    p_asset_tag          in varchar2,
    p_from_status        in varchar2,
    p_to_status          in varchar2,
    p_from_location_id   in number,
    p_to_location_id     in number,
    p_old_related_user_id in number,
    p_new_related_user_id in number,
    p_reason_text        in varchar2,
    p_old_version        in number,
    p_new_version        in number
  ) is
    l_actor_id       number;
    l_correlation_id varchar2(64 char);
    l_recorded_id     varchar2(64 char);
  begin
    l_actor_id := of_security_api.current_user_id();
    l_correlation_id := of_util_api.new_correlation_id();

    insert into of_asset_status_history (
      asset_id, from_status_code, to_status_code,
      from_location_id, to_location_id, related_user_id,
      changed_at, changed_by_user_id, reason_text, correlation_id
    ) values (
      p_asset_id, p_from_status, p_to_status,
      p_from_location_id, p_to_location_id,
      coalesce(p_new_related_user_id, p_old_related_user_id),
      systimestamp, l_actor_id, substr(trim(p_reason_text), 1, 1000),
      l_correlation_id
    );

    l_recorded_id := of_audit_api.record_event(
      p_action_code      => p_action_code,
      p_entity_type_code => 'ASSET',
      p_entity_id        => p_asset_id,
      p_entity_key       => p_asset_tag,
      p_old_values_json  => state_json(
        p_from_status, p_old_version, p_from_location_id,
        p_old_related_user_id
      ),
      p_new_values_json  => state_json(
        p_to_status, p_new_version, p_to_location_id,
        p_new_related_user_id
      ),
      p_correlation_id   => l_correlation_id
    );
  end record_event;

  procedure register_asset(
    p_asset_tag              in  varchar2,
    p_asset_type_id          in  number,
    p_serial_number          in  varchar2 default null,
    p_asset_name             in  varchar2,
    p_description            in  varchar2 default null,
    p_location_id            in  number,
    p_acquisition_date       in  date default null,
    p_purchase_cost          in  number default null,
    p_currency_code          in  varchar2 default null,
    p_warranty_end_date      in  date default null,
    p_asset_id               out number,
    p_row_version            out number
  ) is
    l_actor_name       varchar2(255 char);
    l_asset_tag        varchar2(50 char);
    l_serial_number    varchar2(100 char);
    l_requires_serial  char(1 char);
    l_warranty_months  number;
    l_warranty_end     date;
    l_currency_code    varchar2(3 char);
  begin
    savepoint of_asset_api_action;
    p_asset_id := null;
    p_row_version := null;

    assert_admin;
    assert_text(p_asset_tag, 'Asset tag', 50);
    assert_text(p_asset_name, 'Asset name', 200);
    assert_location(p_location_id);
    validate_money(p_purchase_cost, p_currency_code, l_currency_code);

    l_actor_name := of_security_api.current_username();
    l_asset_tag := of_util_api.normalize_code(p_asset_tag);
    l_serial_number := upper(trim(p_serial_number));

    begin
      select requires_serial_no, default_warranty_months
        into l_requires_serial, l_warranty_months
        from of_asset_types
       where id = p_asset_type_id and is_active = 'Y';
    exception
      when no_data_found then
        fail(-20206, 'The selected asset type is missing or inactive.');
    end;

    if l_requires_serial = 'Y' and l_serial_number is null then
      fail(-20207, 'A serial number is required for this asset type.');
    end if;
    if l_serial_number is not null and length(l_serial_number) > 100 then
      fail(-20200, 'Serial number exceeds 100 characters.');
    end if;
    if p_warranty_end_date is not null and p_acquisition_date is not null
       and p_warranty_end_date < p_acquisition_date then
      fail(-20200, 'Warranty end date cannot precede acquisition date.');
    end if;

    l_warranty_end := p_warranty_end_date;
    if l_warranty_end is null and p_acquisition_date is not null
       and l_warranty_months is not null then
      l_warranty_end := add_months(p_acquisition_date, l_warranty_months);
    end if;

    insert into of_assets (
      asset_tag, asset_type_id, serial_number, asset_name, description,
      status_code, current_location_id, acquisition_date, purchase_cost,
      currency_code, warranty_end_date, row_version, created_by, updated_by
    ) values (
      l_asset_tag, p_asset_type_id, l_serial_number, trim(p_asset_name),
      substr(trim(p_description), 1, 2000), 'IN_STOCK', p_location_id,
      p_acquisition_date, p_purchase_cost, l_currency_code, l_warranty_end,
      1, l_actor_name, l_actor_name
    ) returning id, row_version into p_asset_id, p_row_version;

    record_event(
      'ASSET_REGISTERED', p_asset_id, l_asset_tag,
      null, 'IN_STOCK', null, p_location_id,
      null, null, 'Asset registered', null, p_row_version
    );
  exception
    when others then
      rollback to of_asset_api_action;
      raise;
  end register_asset;

  procedure reserve_asset(
    p_asset_id               in  number,
    p_expected_row_version   in  number,
    p_reserved_for_user_id   in  number,
    p_expires_at             in  timestamp with local time zone default null,
    p_reason_text            in  varchar2 default null,
    p_reservation_id         out number,
    p_new_row_version        out number
  ) is
    l_asset      of_assets%rowtype;
    l_actor_id   number;
    l_actor_name varchar2(255 char);
  begin
    savepoint of_asset_api_action;
    p_reservation_id := null;
    p_new_row_version := null;
    lock_asset(p_asset_id, p_expected_row_version, l_asset);
    if l_asset.status_code <> 'IN_STOCK' then
      fail(-20204, 'Reserve is allowed only while an asset is IN_STOCK.');
    end if;
    assert_user(p_reserved_for_user_id);
    if p_expires_at is not null and p_expires_at <= systimestamp then
      fail(-20200, 'Reservation expiry must be in the future.');
    end if;

    l_actor_id := of_security_api.current_user_id();
    l_actor_name := of_security_api.current_username();
    insert into of_asset_reservations (
      asset_id, reserved_for_user_id, reserved_by_user_id,
      reserved_at, expires_at, status_code, reason_text,
      created_by, updated_by
    ) values (
      l_asset.id, p_reserved_for_user_id, l_actor_id,
      systimestamp, p_expires_at, 'ACTIVE',
      substr(trim(p_reason_text), 1, 1000), l_actor_name, l_actor_name
    ) returning id into p_reservation_id;

    update of_assets
       set status_code = 'RESERVED', row_version = row_version + 1,
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_asset.id
     returning row_version into p_new_row_version;

    record_event(
      'ASSET_RESERVED', l_asset.id, l_asset.asset_tag,
      'IN_STOCK', 'RESERVED', l_asset.current_location_id,
      l_asset.current_location_id, null, p_reserved_for_user_id,
      p_reason_text, l_asset.row_version, p_new_row_version
    );
  exception
    when others then rollback to of_asset_api_action; raise;
  end reserve_asset;

  procedure release_reservation(
    p_asset_id               in  number,
    p_expected_row_version   in  number,
    p_reason_text            in  varchar2,
    p_new_row_version        out number
  ) is
    l_asset         of_assets%rowtype;
    l_reservation_id number;
    l_reserved_for  number;
    l_actor_id      number;
    l_actor_name    varchar2(255 char);
  begin
    savepoint of_asset_api_action;
    p_new_row_version := null;
    assert_text(p_reason_text, 'Release reason', 1000);
    lock_asset(p_asset_id, p_expected_row_version, l_asset);
    if l_asset.status_code <> 'RESERVED' then
      fail(-20204, 'Release is allowed only while an asset is RESERVED.');
    end if;

    select id, reserved_for_user_id
      into l_reservation_id, l_reserved_for
      from of_asset_reservations
     where asset_id = l_asset.id and status_code = 'ACTIVE'
       for update;

    l_actor_id := of_security_api.current_user_id();
    l_actor_name := of_security_api.current_username();
    update of_asset_reservations
       set status_code = 'RELEASED', released_at = systimestamp,
           released_by_user_id = l_actor_id,
           reason_text = substr(trim(p_reason_text), 1, 1000),
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_reservation_id;

    update of_assets
       set status_code = 'IN_STOCK', row_version = row_version + 1,
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_asset.id
     returning row_version into p_new_row_version;

    record_event(
      'RESERVATION_RELEASED', l_asset.id, l_asset.asset_tag,
      'RESERVED', 'IN_STOCK', l_asset.current_location_id,
      l_asset.current_location_id, l_reserved_for, null,
      p_reason_text, l_asset.row_version, p_new_row_version
    );
  exception
    when no_data_found then
      rollback to of_asset_api_action;
      fail(-20208, 'The active reservation is missing.');
    when others then rollback to of_asset_api_action; raise;
  end release_reservation;

  procedure assign_asset(
    p_asset_id               in  number,
    p_expected_row_version   in  number,
    p_assigned_to_user_id    in  number,
    p_condition_out_code     in  varchar2,
    p_to_location_id         in  number default null,
    p_notes                  in  varchar2 default null,
    p_assignment_id          out number,
    p_new_row_version        out number
  ) is
    l_asset          of_assets%rowtype;
    l_condition      varchar2(30 char);
    l_location_id    number;
    l_actor_id       number;
    l_actor_name     varchar2(255 char);
    l_reservation_id number;
    l_reserved_for   number;
  begin
    savepoint of_asset_api_action;
    p_assignment_id := null;
    p_new_row_version := null;
    lock_asset(p_asset_id, p_expected_row_version, l_asset);
    if l_asset.status_code not in ('IN_STOCK', 'RESERVED') then
      fail(-20204, 'Assign is allowed only from IN_STOCK or RESERVED.');
    end if;
    assert_user(p_assigned_to_user_id);
    l_condition := normalized_condition(p_condition_out_code);
    l_location_id := coalesce(p_to_location_id, l_asset.current_location_id);
    assert_location(l_location_id);
    l_actor_id := of_security_api.current_user_id();
    l_actor_name := of_security_api.current_username();

    if l_asset.status_code = 'RESERVED' then
      select id, reserved_for_user_id
        into l_reservation_id, l_reserved_for
        from of_asset_reservations
       where asset_id = l_asset.id and status_code = 'ACTIVE'
         for update;
      if l_reserved_for <> p_assigned_to_user_id then
        fail(-20204, 'The reservation belongs to a different intended custodian.');
      end if;
      update of_asset_reservations
         set status_code = 'FULFILLED', released_at = systimestamp,
             released_by_user_id = l_actor_id,
             updated_at = systimestamp, updated_by = l_actor_name
       where id = l_reservation_id;
    end if;

    insert into of_asset_assignments (
      asset_id, assigned_to_user_id, assigned_by_user_id, assigned_at,
      condition_out_code, notes, created_by, updated_by
    ) values (
      l_asset.id, p_assigned_to_user_id, l_actor_id, systimestamp,
      l_condition, substr(trim(p_notes), 1, 2000), l_actor_name, l_actor_name
    ) returning id into p_assignment_id;

    update of_assets
       set status_code = 'ASSIGNED', current_location_id = l_location_id,
           row_version = row_version + 1,
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_asset.id
     returning row_version into p_new_row_version;

    record_event(
      'ASSET_ASSIGNED', l_asset.id, l_asset.asset_tag,
      l_asset.status_code, 'ASSIGNED', l_asset.current_location_id,
      l_location_id,
      case when l_asset.status_code = 'RESERVED' then l_reserved_for end,
      p_assigned_to_user_id, p_notes,
      l_asset.row_version, p_new_row_version
    );
  exception
    when no_data_found then
      rollback to of_asset_api_action;
      fail(-20208, 'The active reservation is missing.');
    when others then rollback to of_asset_api_action; raise;
  end assign_asset;

