      'ASSET_TRANSFERRED', l_asset.id, l_asset.asset_tag,
      'ASSIGNED', 'ASSIGNED', l_asset.current_location_id, l_location_id,
      l_old_custodian, p_new_custodian_user_id, p_reason_text,
      l_asset.row_version, p_new_row_version
    );
  exception
    when no_data_found then
      rollback to of_asset_api_action;
      fail(-20208, 'The active assignment is missing.');
    when others then rollback to of_asset_api_action; raise;
  end transfer_asset;

  procedure return_asset(
    p_asset_id               in  number,
    p_expected_row_version   in  number,
    p_return_location_id     in  number,
    p_condition_in_code      in  varchar2,
    p_notes                  in  varchar2 default null,
    p_new_row_version        out number
  ) is
    l_asset         of_assets%rowtype;
    l_assignment_id number;
    l_custodian     number;
    l_condition     varchar2(30 char);
    l_actor_id      number;
    l_actor_name    varchar2(255 char);
  begin
    savepoint of_asset_api_action;
    p_new_row_version := null;
    lock_asset(p_asset_id, p_expected_row_version, l_asset);
    if l_asset.status_code <> 'ASSIGNED' then
      fail(-20204, 'Return is allowed only while an asset is ASSIGNED.');
    end if;
    assert_location(p_return_location_id);
    l_condition := normalized_condition(p_condition_in_code);
    select id, assigned_to_user_id
      into l_assignment_id, l_custodian
      from of_asset_assignments
     where asset_id = l_asset.id and returned_at is null
       for update;

    l_actor_id := of_security_api.current_user_id();
    l_actor_name := of_security_api.current_username();
    update of_asset_assignments
       set returned_at = systimestamp, returned_by_user_id = l_actor_id,
           condition_in_code = l_condition,
           notes = substr(
             case when notes is null then '' else notes || chr(10) end ||
             trim(p_notes), 1, 2000
           ),
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_assignment_id;

    update of_assets
       set status_code = 'IN_STOCK', current_location_id = p_return_location_id,
           row_version = row_version + 1,
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_asset.id
     returning row_version into p_new_row_version;

    record_event(
      'ASSET_RETURNED', l_asset.id, l_asset.asset_tag,
      'ASSIGNED', 'IN_STOCK', l_asset.current_location_id,
      p_return_location_id, l_custodian, null, p_notes,
      l_asset.row_version, p_new_row_version
    );
  exception
    when no_data_found then
      rollback to of_asset_api_action;
      fail(-20208, 'The active assignment is missing.');
    when others then rollback to of_asset_api_action; raise;
  end return_asset;

  procedure open_repair(
    p_asset_id               in  number,
    p_expected_row_version   in  number,
    p_problem_description    in  clob,
    p_provider_name          in  varchar2 default null,
    p_repair_location_id     in  number default null,
    p_condition_in_code      in  varchar2 default null,
    p_repair_id              out number,
    p_new_row_version        out number
  ) is
    l_asset          of_assets%rowtype;
    l_assignment_id  number;
    l_old_custodian  number;
    l_condition      varchar2(30 char);
    l_location_id    number;
    l_actor_id       number;
    l_actor_name     varchar2(255 char);
  begin
    savepoint of_asset_api_action;
    p_repair_id := null;
    p_new_row_version := null;
    assert_clob_text(p_problem_description, 'Problem description');
    lock_asset(p_asset_id, p_expected_row_version, l_asset);
    if l_asset.status_code not in ('IN_STOCK', 'ASSIGNED') then
      fail(-20204, 'Repair may be opened only from IN_STOCK or ASSIGNED.');
    end if;
    l_location_id := coalesce(p_repair_location_id, l_asset.current_location_id);
    assert_location(l_location_id);
    l_actor_id := of_security_api.current_user_id();
    l_actor_name := of_security_api.current_username();
    l_old_custodian := null;

    if l_asset.status_code = 'ASSIGNED' then
      if p_condition_in_code is null then
        fail(-20200, 'Condition in is required when repair closes active custody.');
      end if;
      l_condition := normalized_condition(p_condition_in_code);
      select id, assigned_to_user_id
        into l_assignment_id, l_old_custodian
        from of_asset_assignments
       where asset_id = l_asset.id and returned_at is null
         for update;
      update of_asset_assignments
         set returned_at = systimestamp, returned_by_user_id = l_actor_id,
             condition_in_code = l_condition,
             notes = substr(
               case when notes is null then '' else notes || chr(10) end ||
               'Sent to repair', 1, 2000
             ),
             updated_at = systimestamp, updated_by = l_actor_name
       where id = l_assignment_id;
    elsif p_condition_in_code is not null then
      fail(-20200, 'Condition in applies only when closing active custody.');
    end if;

    insert into of_asset_repairs (
      asset_id, status_code, problem_description, provider_name_snapshot,
      opened_at, row_version, created_by, updated_by
    ) values (
      l_asset.id, 'OPEN', p_problem_description,
      substr(trim(p_provider_name), 1, 200), systimestamp, 1,
      l_actor_name, l_actor_name
    ) returning id into p_repair_id;

    update of_assets
       set status_code = 'IN_REPAIR', current_location_id = l_location_id,
           row_version = row_version + 1,
           updated_at = systimestamp, updated_by = l_actor_name
     where id = l_asset.id
     returning row_version into p_new_row_version;

    record_event(
      'ASSET_REPAIR_OPENED', l_asset.id, l_asset.asset_tag,
      l_asset.status_code, 'IN_REPAIR', l_asset.current_location_id,
      l_location_id, l_old_custodian, null,
      dbms_lob.substr(p_problem_description, 1000, 1),
      l_asset.row_version, p_new_row_version
    );
  exception
    when no_data_found then
      rollback to of_asset_api_action;
      fail(-20208, 'The active assignment is missing.');
    when others then rollback to of_asset_api_action; raise;
  end open_repair;

  procedure close_repair(
    p_asset_id               in  number,
    p_repair_id              in  number,
    p_resolution_description in  clob,
    p_cost_amount            in  number,
    p_currency_code          in  varchar2,
    p_actor_name             in  varchar2,
    p_currency_normalized    out varchar2
  ) is
    l_found number;
  begin
    assert_clob_text(p_resolution_description, 'Resolution description');
    validate_money(p_cost_amount, p_currency_code, p_currency_normalized);
    begin
      select id into l_found
        from of_asset_repairs
       where id = p_repair_id
         and asset_id = p_asset_id
         and status_code in ('OPEN', 'IN_PROGRESS')
         for update;
    exception
      when no_data_found then
        fail(-20209, 'The selected active repair does not match this asset.');
    end;

    update of_asset_repairs
       set status_code = 'COMPLETED',
           resolution_description = p_resolution_description,
           closed_at = systimestamp, cost_amount = p_cost_amount,
           currency_code = p_currency_normalized,
           row_version = row_version + 1,
           updated_at = systimestamp, updated_by = p_actor_name
     where id = p_repair_id;
  end close_repair;

  procedure complete_repair_to_stock(
