begin
  select count(*)
    into l_base_table_count
    from user_tables
   where table_name in (
     'OF_LOCATIONS', 'OF_APP_USERS', 'OF_ROLES', 'OF_USER_ROLES',
     'OF_AUDIT_LOG'
