    select
      (select count(*) from of_app_users
        where upper(username) in ('LAYLA.EMPLOYEE', 'YOUSSEF.EMPLOYEE')
          and is_active = 'Y')
      +
      (select count(*) from of_locations
        where code in ('CAI-HQ', 'ALX-OFFICE') and is_active = 'Y')
